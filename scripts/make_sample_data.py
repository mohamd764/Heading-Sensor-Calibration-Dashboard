"""Generate the synthetic demo job in ``sample_data/sample_job.json``.

Everything here is fictional: round-number coordinates in WGS 84 / UTM 15N
(chosen only so the grid convergence is clearly non-zero), invented names,
and observations simulated from a known heading-sensor bias so the app's
output can be checked against the truth.

    python scripts/make_sample_data.py
"""

from __future__ import annotations

import json
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from heading_calibration.geodesy import (  # noqa: E402
    grid_bearing,
    grid_convergence,
    normalize_0_360,
    resolve_projected_crs,
)

SEED = 20240101
TRUE_C_MINUS_O = 0.35  # simulated sensor error (degrees): sensor reads 0.35° low
ZONE, HEMISPHERE = 15, "North"
STATION = ("STN-A", 250000.000, 3300000.000, 3.215)
BACKSIGHT = ("STN-B", 249879.512, 3300310.184, 2.874)
BACKSIGHT_READING = (0, 0, 0.0)
BOW_STEM_SEPARATION = 84.600  # metres between bow and stem prisms
EPOCHS = 10


def to_dms(angle):
    total = round(normalize_0_360(angle) * 3600)
    d, rem = divmod(total, 3600)
    m, s = divmod(rem, 60)
    return int(d) % 360, int(m), float(s)


def main():
    rng = random.Random(SEED)
    crs = resolve_projected_crs(zone=ZONE, hemisphere=HEMISPHERE)
    _, e0, n0, _ = STATION
    _, eb, nb, _ = BACKSIGHT
    gamma = grid_convergence(crs, e0, n0)
    bs_bearing = grid_bearing(e0, n0, eb, nb)
    bs_dir = BACKSIGHT_READING[0] + BACKSIGHT_READING[1] / 60 + BACKSIGHT_READING[2] / 3600

    rows = []
    for k in range(EPOCHS):
        true_heading = 47.50 + 0.15 * math.sin(k / 2.0)  # vessel yawing slightly at the berth
        grid_heading = math.radians(true_heading - gamma)
        centre_e = e0 + 62.0 + 0.05 * k
        centre_n = n0 + 18.0 - 0.03 * k
        half = BOW_STEM_SEPARATION / 2
        bow = (centre_e + half * math.sin(grid_heading), centre_n + half * math.cos(grid_heading))
        stem = (centre_e - half * math.sin(grid_heading), centre_n - half * math.cos(grid_heading))
        observed = round(true_heading - TRUE_C_MINUS_O + rng.gauss(0, 0.03), 2)

        minute, second = divmod(30 * k, 60)
        for label, (e, n), offset, obs in (("Bow", bow, 0, observed), ("Stem", stem, 5, None)):
            bearing = grid_bearing(e0, n0, e, n) + rng.gauss(0, 2 / 3600)
            distance = math.hypot(e - e0, n - n0) + rng.gauss(0, 0.002)
            d, m, s = to_dms(bs_dir + bearing - bs_bearing)
            rows.append({
                "utc_time": f"14:{minute:02d}:{second + offset:02d}",
                "obs_point": label,
                "direction_deg": d,
                "direction_min": m,
                "direction_sec": s,
                "obs_distance": round(distance, 3),
                "obs_true_heading": obs,
            })

    job = {
        "_note": "Synthetic demo data generated by scripts/make_sample_data.py. All names and values are fictional.",
        "job": {
            "job_number": "DEMO-0001",
            "job_description": "Gyrocompass calibration (demo)",
            "client": "Example Marine Co. (fictional)",
            "party_chief": "J. Doe",
            "surveyor": "A. Smith",
            "wharf": "Berth 1 (fictional)",
            "vessel": "MV Sample Vessel",
            "date": "2024-01-01",
            "device_name": "Gyro-1 (demo)",
        },
        "crs": {"mode": "utm", "zone": ZONE, "hemisphere": HEMISPHERE, "epsg": None},
        "instrument": dict(zip(("name", "easting", "northing", "height"), STATION)),
        "backsight": dict(zip(("name", "easting", "northing", "height"), BACKSIGHT)),
        "backsight_observation": dict(zip(("deg", "min", "sec"), BACKSIGHT_READING)),
        "observations": rows,
        "expected": {"mean_c_minus_o_deg": TRUE_C_MINUS_O, "grid_convergence_deg": round(gamma, 6)},
    }
    out = ROOT / "sample_data" / "sample_job.json"
    out.write_text(json.dumps(job, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {out.relative_to(ROOT)}  (grid convergence {gamma:+.4f}°)")


if __name__ == "__main__":
    main()
